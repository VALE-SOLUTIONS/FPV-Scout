#!/usr/bin/env python3
"""Generate the scanner's 4-bit antialiased Inter atlas. Requires Pillow.

Font: tools/fonts/Inter.ttf (SIL OFL, adjacent OFL.txt). No font library is
needed on the device. Re-run after changing sizes or the source font.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'espsoup/components/cyd_c5/cyd_font_smooth_data.h'
SPECS = [(12,400),(14,500),(18,600),(36,600)]


def font(size, weight):
    f = ImageFont.truetype(str(ROOT/'tools/fonts/Inter.ttf'),size)
    f.set_variation_by_axes([14,weight])
    return f


def generate():
    out = ['/* Generated by tools/generate_scout_font.py. Inter font: SIL OFL-1.1. */',
           '#pragma once', '#include <stdint.h>',
           'typedef struct { uint32_t offset; uint8_t w,h,advance; int8_t left,top; } cyd_glyph_t;',
           'typedef struct { const cyd_glyph_t *glyphs; const uint8_t *pixels; uint8_t height; } cyd_smooth_font_t;']
    for index,(size,weight) in enumerate(SPECS):
        f = font(size,weight)
        ascent,descent = f.getmetrics()
        glyphs,pixels = [],[]
        for code in range(32,127):
            c = chr(code)
            left,top,right,bottom = f.getbbox(c,anchor='ls')
            w,h = right-left,bottom-top
            advance = round(f.getlength(c))
            assert 0 <= w <= 255 and 0 <= h <= 255 and 0 < advance <= 255
            assert -128 <= left <= 127 and -128 <= top+ascent <= 127
            image=Image.new('L',(max(1,w),max(1,h)))
            ImageDraw.Draw(image).text((-left,-top),c,font=f,anchor='ls',fill=255)
            values=[(v*15+127)//255 for v in image.tobytes()] if w and h else []
            glyphs.append((len(pixels),w,h,advance,left,top+ascent))
            pixels.extend((values[j]<<4)|(values[j+1] if j+1<len(values) else 0) for j in range(0,len(values),2))
        out.append(f'static const cyd_glyph_t cyd_glyphs_{index}[95] = {{')
        out.extend('    {'+','.join(map(str,g))+'},' for g in glyphs)
        out.append('};')
        out.append(f'static const uint8_t cyd_pixels_{index}[{len(pixels)}] = {{')
        out.extend('    '+','.join(map(str,pixels[j:j+24]))+',' for j in range(0,len(pixels),24))
        out.append('};')
    out.append('static const cyd_smooth_font_t cyd_smooth_fonts[4] = {')
    for index,(size,weight) in enumerate(SPECS):
        a,d=font(size,weight).getmetrics()
        out.append(f'    {{cyd_glyphs_{index},cyd_pixels_{index},{a+d}}},')
    out.append('};')
    DEST.write_text('\n'.join(out)+'\n',encoding='utf-8')
    print('Generated',DEST)


if __name__ == '__main__': generate()
